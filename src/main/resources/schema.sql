CREATE TABLE IF NOT EXISTS validation_run (
    id VARCHAR(36) PRIMARY KEY,
    release_label VARCHAR(100) NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    started_at VARCHAR(40),
    finished_at VARCHAR(40),
    status VARCHAR(20) NOT NULL,
    window_seconds INTEGER NOT NULL,
    interval_seconds INTEGER NOT NULL,
    component_ids VARCHAR(2000) NOT NULL,
    message VARCHAR(1000) NOT NULL DEFAULT '',
    notification_status VARCHAR(40) NOT NULL DEFAULT 'PENDING'
);
CREATE TABLE IF NOT EXISTS check_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(36) NOT NULL REFERENCES validation_run(id) ON DELETE CASCADE,
    component VARCHAR(40) NOT NULL,
    checked_at VARCHAR(40) NOT NULL,
    success BOOLEAN NOT NULL,
    http_status INTEGER NOT NULL,
    latency_ms BIGINT NOT NULL,
    attempts INTEGER NOT NULL,
    message VARCHAR(1000) NOT NULL,
    evidence CLOB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_check_run ON check_result(run_id, id);
CREATE INDEX IF NOT EXISTS idx_run_created ON validation_run(created_at);
